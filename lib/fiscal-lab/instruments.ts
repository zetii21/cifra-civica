/**
 * Revenue instruments of the national laboratory beyond IRPF. Baseline
 * revenue figures are rounded, reviewed public aggregates (AEAT annual
 * collection report 2024; regional ceded-tax statistics 2023) and are always
 * presented as an approximate reference, never as official liquidations.
 * Incidence profiles are stylised household-survey (EPF/ECV) patterns.
 */
import { consumptionWeights, gdpWeights, populationWeights } from "./demography";
import type {
  CommunityCode,
  IncidenceProfile,
  InstrumentDefinition,
} from "./types";

function normalise(values: number[]): number[] {
  const total = values.reduce((sum, value) => sum + value, 0);
  return values.map((value) => value / total);
}

function incidence(
  deciles: number[],
  familyTypes: number[],
  ageBands: number[],
): IncidenceProfile {
  return {
    deciles: normalise(deciles),
    familyTypes: normalise(familyTypes),
    ageBands: normalise(ageBands),
  };
}

