function scaledWeights(
  base: Record<CommunityCode, number>,
  overrides: Partial<Record<CommunityCode, number>> = {},
): Record<CommunityCode, number> {
  const merged = { ...base, ...overrides } as Record<CommunityCode, number>;
  const total = Object.values(merged).reduce((sum, value) => sum + value, 0);
  return Object.fromEntries(
    Object.entries(merged).map(([code, value]) => [code, value / total]),
  ) as Record<CommunityCode, number>;
}

